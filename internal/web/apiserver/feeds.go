// feedStates reads the stored state of every registered feed, in Feeds order.
func (s *Server) feedStates(ctx context.Context) ([]store.FeedState, error) {
	out := make([]store.FeedState, 0, len(s.o.Feeds))
	for _, f := range s.o.Feeds {
		st, err := s.o.Store.FeedState(ctx, f.Name)
		if err != nil {
			return nil, err
		}
		out = append(out, st)
	}
	return out, nil
}

// stale reports whether a feed's last success is missing or older than its threshold.
func stale(st store.FeedState, f FeedInfo, now time.Time) bool {
	return st.LastSuccess.IsZero() || now.Sub(st.LastSuccess) > f.StaleAfter
}

// freshness summarises the feeds: the stale ones in Feeds order, and the earliest last success.
func (s *Server) freshness(ctx context.Context) (apigen.FeedFreshness, error) {
	states, err := s.feedStates(ctx)
	if err != nil {
		return apigen.FeedFreshness{}, err
	}
	now := s.o.Now()
	out := apigen.FeedFreshness{Stale: []string{}}
	var oldest time.Time
	for i, st := range states {
		if stale(st, s.o.Feeds[i], now) {
			out.Stale = append(out.Stale, st.Name)
		}
		if !st.LastSuccess.IsZero() && (oldest.IsZero() || st.LastSuccess.Before(oldest)) {
			oldest = st.LastSuccess
		}
	}
	out.Fresh, out.OldestSuccess = len(out.Stale) == 0, optTime(oldest)
	return out, nil
}

// ListFeeds lists the registered feeds with their last sync, and every data source.
func (s *Server) ListFeeds(ctx context.Context, _ apigen.ListFeedsRequestObject) (apigen.ListFeedsResponseObject, error) {
	states, err := s.feedStates(ctx)
	if err != nil {
		return nil, err
	}
	now := s.o.Now()
	feeds := make([]apigen.Feed, 0, len(states))
	for i, st := range states {
		f := s.o.Feeds[i]
		feeds = append(feeds, apigen.Feed{Name: f.Name, LastSuccess: optTime(st.LastSuccess), LastAttempt: optTime(st.LastAttempt),
			LastError: st.LastError, StaleAfter: f.StaleAfter.String(), Stale: stale(st, f, now)})
	}
	sources := make([]apigen.Source, 0, len(Sources))
	for _, src := range Sources {
		sources = append(sources, apigen.Source{Name: src.Name, Feed: src.Feed, Licence: src.Licence, Attribution: src.Attribution, Url: src.URL})
	}
	cluster, at := s.stamp()
	return apigen.ListFeeds200JSONResponse{Cluster: cluster, GeneratedAt: at, Feeds: feeds, Sources: sources}, nil
}

// ListExceptions lists the Exception resources, by namespace and name.
func (s *Server) ListExceptions(ctx context.Context, _ apigen.ListExceptionsRequestObject) (apigen.ListExceptionsResponseObject, error) {
	out := []apigen.Exception{}
	if s.o.Kube != nil {
		var list v1alpha1.ExceptionList
		if err := s.o.Kube.List(ctx, &list); err != nil {
			return nil, fmt.Errorf("list exceptions: %w", err)
		}
		for _, e := range list.Items {
			out = append(out, apigen.Exception{
				Id: e.Namespace + "/" + e.Name, Namespace: e.Namespace, Name: e.Name, Reason: e.Spec.Reason,
				Expires: e.Spec.Expires.UTC(), Advisories: nz(e.Spec.Advisories), Packages: nz(e.Spec.Packages),
				ImageRepositories: nz(e.Spec.ImageRepositories), Owners: nz(e.Spec.Owners), VexStatus: optString(e.Spec.VEXStatus),
				Justification: optString(e.Spec.Justification), MatchedFindings: int(e.Status.MatchedFindings),
				UrgentNotExcepted: int(e.Status.UrgentNotExcepted), Expired: e.Status.Expired,
			})
		}
		slices.SortFunc(out, func(a, b apigen.Exception) int { return cmp.Compare(a.Id, b.Id) })
	}
	cluster, at := s.stamp()
	return apigen.ListExceptions200JSONResponse{Cluster: cluster, GeneratedAt: at, Exceptions: out}, nil
}

// GetSettings is the configuration that shapes what ffs reports. Deployment details (registry,
// listen address, allowed hosts, paths, catalogue) are left out.
func (s *Server) GetSettings(_ context.Context, _ apigen.GetSettingsRequestObject) (apigen.GetSettingsResponseObject, error) {
	c := s.o.Config
	byName := c.Feeds.ByName()
	feeds := make([]apigen.FeedSettings, 0, len(byName))
	for _, name := range slices.Sorted(maps.Keys(byName)) {
		f := byName[name]
		feeds = append(feeds, apigen.FeedSettings{Name: name, Enabled: f.Enabled, Interval: f.Interval.String(), StaleAfter: f.StaleAfter.String()})
	}
	annotations := map[string]string{}
	maps.Copy(annotations, c.Exposure.InternalLBAnnotations)
	cluster, at := s.stamp()
	return apigen.GetSettings200JSONResponse{
		Cluster: cluster, GeneratedAt: at, Version: version.Version, ClusterName: c.ClusterName, Feeds: feeds,
		Priority: apigen.PrioritySettings{EpssHigh: c.Priority.EPSSHigh, EpssBump: c.Priority.EPSSBump},
		Exposure: apigen.ExposureSettings{
			InternalIngressClasses: nz(c.Exposure.InternalIngressClasses), InternalGatewayClasses: nz(c.Exposure.InternalGatewayClasses),
			InternalGateways: nz(c.Exposure.InternalGateways), InternalLBAnnotations: annotations,
		},
		Crd:         apigen.CrdSettings{MinPriority: c.CRD.MinPriority, MaxFindings: c.CRD.MaxFindings},
		Events:      apigen.EventsSettings{MinPriority: c.Events.MinPriority},
		OpenReports: apigen.OpenReportsSettings{Mode: c.OpenReports.Mode},
		Exceptions:  apigen.ExceptionSettings{MaxDuration: c.Exceptions.MaxDuration.String()},
		Retention:   apigen.RetentionSettings{Resolved: c.Retention.Resolved.String()},
		Upgrades:    apigen.UpgradeSettings{Enabled: c.Upgrades.Enabled, DailyAt: c.Upgrades.DailyAt},
	}, nil
}
